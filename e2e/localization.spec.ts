import { expect, test } from '@playwright/test'

test('interface language changes real drafting and file controls and survives reload', async ({ page }) => {
  await page.goto('/')
  const language = page.getByTestId('interface-language').first()
  await expect(language).toBeVisible()
  await language.selectOption('ja')
  await expect(page.getByTestId('ribbon-tab-draft')).toHaveText('作図')
  await page.getByTestId('ribbon-tab-output').click()
  await expect(page.getByTestId('ribbon-command-save-json')).toHaveText('保存')
  await page.reload()
  await expect(page.getByTestId('interface-language').first()).toHaveValue('ja')
  await expect(page.getByTestId('ribbon-tab-draft')).toHaveText('作図')
  await page.getByTestId('interface-language').first().selectOption('de')
  await expect(page.getByTestId('ribbon-tab-draft')).toHaveText('Zeichnen')
  await expect(page.locator('html')).toHaveAttribute('lang', 'de')
})

test('phone options expose a working language selector', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Options', exact: true }).click()
  const language = page.getByTestId('interface-language').first()
  await expect(language).toBeVisible()
  await language.selectOption('ja')
  await expect(page.getByRole('button', { name: 'プロジェクトメモ', exact: true })).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('lang', 'ja')
})

test('localized print controls keep paper identifiers and remain reachable on a phone', async ({ page }, testInfo) => {
  await page.goto('/')
  await page.getByTestId('interface-language').first().selectOption('ja')
  await page.getByTestId('ribbon-tab-output').click()
  await page.getByTestId('ribbon-command-print-preview').click()
  const dialog = page.getByRole('dialog', { name: '印刷プレビュー・分割印刷' })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByLabel('用紙', { exact: true })).toHaveValue('letter')
  await expect(dialog.getByLabel('用紙', { exact: true }).locator('option[value=letter]')).toHaveText('レター（215.9 × 279.4 mm）')
  await dialog.getByLabel('縮尺 (%)', { exact: true }).fill('125')
  await expect(dialog.getByLabel('縮尺 (%)', { exact: true })).toHaveValue('125')
  await dialog.screenshot({ path: testInfo.outputPath('print-japanese-desktop.png') })
  await page.setViewportSize({ width: 390, height: 844 })
  const openTiles = dialog.getByRole('button', { name: '印刷用ページを開く', exact: true })
  await openTiles.scrollIntoViewIfNeeded()
  await expect(openTiles).toBeInViewport()
  expect(await dialog.evaluate(node => node.scrollWidth <= node.clientWidth + 1)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('print-japanese-phone.png') })
  await page.setViewportSize({ width: 1280, height: 900 })
  await dialog.getByRole('button', { name: '完了', exact: true }).click()
  await page.getByTestId('interface-language').first().selectOption('de')
  await page.getByTestId('ribbon-command-print-preview').click()
  const german = page.getByRole('dialog', { name: 'Druckvorschau und Seitenaufteilung' })
  await expect(german.getByLabel('Papier', { exact: true })).toHaveValue('letter')
  await expect(german.getByLabel('Maßstab (%)', { exact: true })).toHaveValue('125')
  await page.setViewportSize({ width: 390, height: 844 })
  const germanAction = german.getByRole('button', { name: 'Druckseiten öffnen', exact: true })
  await germanAction.scrollIntoViewIfNeeded()
  await expect(germanAction).toBeInViewport()
  expect(await german.evaluate(node => node.scrollWidth <= node.clientWidth + 1)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('print-german-phone.png') })
})

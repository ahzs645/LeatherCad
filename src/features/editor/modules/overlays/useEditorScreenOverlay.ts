    showStitchSimulatorModal,
    setShowStitchSimulatorModal,
    showBoxStitchHelperModal,
    setShowBoxStitchHelperModal,
    showBoxStitchModal,
    setShowBoxStitchModal,
    showMandalaModal,
    setShowMandalaModal,
    showWizardModal,

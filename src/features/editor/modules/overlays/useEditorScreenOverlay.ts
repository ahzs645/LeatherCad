import type { Dispatch, SetStateAction } from 'react'
import type { UseEditorScreenShellsParams } from '../../editorScreenShellTypes'
import type { BoxStitchHelperSettings } from '../../ops/box-stitch-settings'
import type { StitchSimulatorSettings } from '../../ops/stitch-simulator-ops'

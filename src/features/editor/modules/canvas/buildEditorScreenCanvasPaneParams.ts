import type { HandlePointKey } from '../../hooks/useCanvasInteractions'
import type { UseEditorScreenShellsParams } from '../../editorScreenShellTypes'
import { buildCanvasPaneParams } from './buildCanvasPaneParams'

export function buildEditorScreenCanvasPaneParams({
  resolvedThemeMode,
  documentState,
  uiState,
  selectionState,
  panelState,
  layerState,
  toolState,
  viewportState,
  screenRefs,
  derivedState,
  canvasController,
  patternPieceSelection,
  printPreviewState,
  previewElement,
  outlineChains,
  stitchSimulatorSettings,
  actions,
  highlightActiveLayerId,
  drawEdges,
  drawFirstPos,
}: UseEditorScreenShellsParams & {
  highlightActiveLayerId?: string | null
  drawEdges?: boolean
  drawFirstPos?: boolean
}) {
  const {
    shapes,
    lineTypes,
    foldLines,
    dimensionLines,
    leatherImageFills,
    tracingOverlays,
    setTracingOverlays,
    backdrops,
    setBackdrops,
    activeBackdropId,
    setActiveBackdropId,
    showAnnotations,
    showCanvasRuler,
    showDimensions,
  } = documentState
  const {
    showGrid,
    gridBackgroundMode,
    displayUnit,
    gridSpacing,
    constraintSuggestions,
    sketchWorkspaceMode,
    legendMode,
    setLegendMode,
    leatherSimEnabled,
    customRotationPivot,
  } = uiState
  const { selectedStitchHoleId, selectedHardwareMarkerId } = selectionState
  const { showPrintAreas } = panelState
  const { layers, activeLayerId } = layerState
  const { setShapes } = documentState
  const { tool, showStitchSequenceLabels } = toolState
  const { viewport } = viewportState
  const { svgRef } = screenRefs
  const {
    lineTypesById,
    selectedShapeIdSet,
    selectedStitchHole,
    workspaceEditableShapes,
    workspaceLinkedShapes,
    workspaceStitchHoles,
    workspaceHardwareMarkers,
    seamGuides,
    annotationLabels,
    pieceGrainlineSegments,
    pieceNotchLines,
    piecePlacementGuides,
    layerStackLevels,
    layerColorsById,
    stackLegendEntries,
    displayLayerColorsById,
    fallbackLayerStroke,
    cutStrokeColor,
    stitchStrokeColor,
    foldStrokeColor,
  } = derivedState
  const { pieceEdgeLabels } = patternPieceSelection
  const { printOutputPlan } = printPreviewState
  const {
    handleZoomStep,
    handleFitView,
    handleResetView,
    handlePointerDown,
    handleShapePointerDown,
    handleShapeHandlePointerDown,
    handleStitchHolePointerDown,
    handleHardwarePointerDown,
    handlePointerMove,
    handlePointerUp,
    interactionPreview,
  } = canvasController
  const {
    selectionActions,
    geometryActions,
    creationController,
    transformActions,
    layerActions,
  } = actions
  const {
    handleDuplicateSelection,
    handleDeleteSelection,
    handleSendSelectionToBack,
    handleBringSelectionToFront,
  } = selectionActions
  const {
    handleConvertSelectionToPath,
    handleMakeBezierCpFlat,
    handleMakeBezierCpSameLength,
    handleMakeBezierCpSymmetric,
    handleSmoothBezierJointAtControl,
  } = geometryActions
  const {
    stitchSimulatorResult,
    handleMarkSelectedStitchHoleAsEnd,
    handleClearSelectedStitchHoleEnd,
  } = creationController
  const effectiveGridBackgroundMode = gridBackgroundMode === 'theme' ? resolvedThemeMode : gridBackgroundMode

  return buildCanvasPaneParams({
    svgRef,
    onPointerDown: handlePointerDown,
    onPointerMove: handlePointerMove,
    onPointerUp: handlePointerUp,
    showGrid,
    gridBackgroundMode: effectiveGridBackgroundMode,
    setTracingOverlays,
    setBackdrops,
    setActiveBackdropId,
    shapes,
    selectedStitchHole,
    handleBringSelectionToFront,
    handleSendSelectionToBack,
    handleDuplicateSelection,
    handleConvertSelectionToPath,
    handleDeleteSelection,
    handleMakeBezierCpFlat,
    handleMakeBezierCpSameLength,
    handleMakeBezierCpSymmetric,
    handleClearSelectedStitchHoleEnd,
    handleMarkSelectedStitchHoleAsEnd,
    contextMenuHandlers: {
      handleCopySelection: selectionActions.handleCopySelection,
      handleCutSelection: selectionActions.handleCutSelection,
      handlePasteClipboard: () => { void selectionActions.handlePasteClipboard() },
      handleSelectAllShapes: selectionActions.handleSelectAllShapes,
      handleMoveSelectionForward: selectionActions.handleMoveSelectionForward,
      handleMoveSelectionBackward: selectionActions.handleMoveSelectionBackward,
      handleGroupSelection: selectionActions.handleGroupSelection,
      handleUngroupSelection: selectionActions.handleUngroupSelection,
      handleRotateSelection: selectionActions.handleRotateSelection,
      handleFlipSelection: transformActions.handleFlipSelection,
      handleSetAsRotationCenter: transformActions.handleSetAsRotationCenter,
      handleClearRotationCenter: transformActions.handleClearRotationCenter,
      handleMakeSelectedLineHorizontal: transformActions.handleMakeSelectedLineHorizontal,
      handleMakeSelectedLineVertical: transformActions.handleMakeSelectedLineVertical,
      handleConvertArcToBezier: geometryActions.handleConvertArcToBezier,
      handleSetSelectionLocked: (locked: boolean) => {
        setShapes((previous) => previous.map((shape) => (selectedShapeIdSet.has(shape.id) ? { ...shape, locked } : shape)))
      },
      handleMoveSelectedShapesToLayerBelow: layerActions.handleMoveSelectedShapesToLayerBelow,
      handleDuplicateSelectedShapesOnBelowLayer: layerActions.handleDuplicateSelectedShapesOnBelowLayer,
      handleMoveSelectedShapesToActiveLayer: layerActions.handleMoveSelectedShapesToActiveLayer,
      handleActivateLayerOfSelectedShape: layerActions.handleActivateLayerOfSelectedShape,
      handleFitView,
    },
    contextMenuState: { hasCustomRotationPivot: customRotationPivot !== null, activeLayerId, layerCount: layers.length },
    viewport,
    displayUnit,
    gridSpacing,
    showCanvasRuler,
    showDimensions,
    handleZoomStep,
    onFitView: handleFitView,
    onResetView: handleResetView,
    tracingOverlays,
    leatherImageFills,
    backdrops,
    activeBackdropId,
    showPrintAreas,
    dimensionLines,
    printPlan: printOutputPlan,
    seamGuides,
    pieceEdgeLabels,
    showAnnotations,
    pieceGrainlineSegments,
    pieceNotchLines,
    piecePlacementGuides,
    visibleShapes: workspaceEditableShapes,
    linkedShapes: workspaceLinkedShapes,
    sketchWorkspaceMode,
    lineTypes,
    lineTypesById,
    selectedShapeIdSet,
    stitchStrokeColor,
    foldStrokeColor,
    cutStrokeColor,
    displayLayerColorsById,
    layerStackLevels,
    onShapePointerDown: handleShapePointerDown,
    onShapeHandlePointerDown: handleShapeHandlePointerDown,
    onShapeHandleDoubleClick: (shapeId: string, pointKey: HandlePointKey) => {
      if (pointKey !== 'control') return
      handleSmoothBezierJointAtControl(shapeId)
    },
    tool,
    visibleStitchHoles: workspaceStitchHoles,
    selectedStitchHoleId,
    showStitchSequenceLabels,
    onStitchHolePointerDown: handleStitchHolePointerDown,
    stitchSimulatorResult,
    stitchSimulatorSettings,
    hideRawStitchHoles: leatherSimEnabled && stitchSimulatorSettings.showSimulatorPattern,
    visibleHardwareMarkers: workspaceHardwareMarkers,
    selectedHardwareMarkerId,
    onHardwarePointerDown: handleHardwarePointerDown,
    foldLines,
    annotationLabels,
    constraintSuggestions,
    previewElement,
    interactionPreview,
    showLayerLegend: false,
    legendMode,
    onSetLegendMode: setLegendMode,
    layers,
    layerColorsById,
    fallbackLayerStroke,
    stackLegendEntries,
    outlineChains,
    highlightActiveLayerId,
    drawEdges,
    drawFirstPos,
  })
}

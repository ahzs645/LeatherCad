import type { UseEditorScreenShellsParams } from '../../editorScreenShellTypes'
import { useEditorWorkbenchController } from '../../controllers/useEditorWorkbenchController'
import {
  buildDocumentInspectorProps,
  buildPieceInspectorContentProps,
  buildSelectionInspectorProps,
} from '../../view-models/buildWorkbenchInspectorViewModels'
import {
  buildWorkbenchProps,
  buildWorkbenchThreeWorkspaceProps,
} from './buildWorkbenchShellViewModels'

export function useEditorScreenWorkbenchModels({
  resolvedThemeMode,
  documentState,
  uiState,
  selectionState,
  panelState,
  layerState,
  toolState,
  viewportState,
  workbenchShellState,
  screenRefs,
  derivedState,
  canvasController,
  patternPieceSelection,
  selectedEditableShape,
  actions,
}: UseEditorScreenShellsParams) {
  const {
    documentName,
    lineTypes,
    setLineTypes,
    setActiveLineTypeId,
    shapes,
    foldLines,
    sketchGroups,
    activeSketchGroupId,
    setActiveSketchGroupId,
    patternPieces,
    pieceInterfaces,
    assemblyConnections,
    pieceLabels,
    piecePlacementLabels,
    piecePlacements3d,
    setPiecePlacements3d,
    seamConnections,
    hardwareMarkers,
    setSeamConnections,
    seamAllowances,
    pieceNotches,
    setPieceNotches,
    snapSettings,
    setSnapSettings,
    showAnnotations,
    setShowAnnotations,
    tracingOverlays,
    setTracingOverlays,
    activeTracingOverlayId,
    setActiveTracingOverlayId,
    projectMemo,
    setProjectMemo,
    stitchThreadColor,
    setStitchThreadColor,
    threePreviewSettings,
    setThreePreviewSettings,
    avatars,
    setAvatars,
    threeTextureSource,
    setThreeTextureSource,
    threeTextureShapeIds,
    setThreeTextureShapeIds,
    leatherImageFills,
    activeLeatherImageFillId,
    setActiveLeatherImageFillId,
    showCanvasRuler,
    setShowCanvasRuler,
    showDimensions,
    setShowDimensions,
  } = documentState
  const {
    isMobileLayout,
    workbenchRibbonTab,
    setWorkbenchRibbonTab,
    workspaceMode,
    setWorkspaceMode,
    setSecondaryPreviewMode,
    displayUnit,
    setDisplayUnit,
    gridSpacing,
    setGridSpacing,
    sketchWorkspaceMode,
    setSketchWorkspaceMode,
    themeMode,
    setShowNestingModal,
    setShowChangeShapeSizeModal,
    setShowStitchSimulatorModal,
    setShowBoxStitchHelperModal,
    setShowBoxStitchModal,
    setShowWizardModal,
    setShowMandalaModal,
    setShowLetterStampModal,
    setShowPrecisionModal,
    setShowMoveCopyDistanceModal,
    setMoveCopyDistanceMode,
    setShowOptionsModal,
  } = uiState
  const { selectedShapeIds, setSelectedShapeIds } = selectionState
  const {
    setShowTracingModal,
    setShowAiBuilderModal,
    setShowHelpModal,
    setShowTemplateRepositoryModal,
    setShowLocalProjectsModal,
    setShowPrintPreviewModal,
    setShowExportModal,
    setShowExportOptionsModal,
  } = panelState
  const {
    layers,
    setLayers,
    activeLayerId,
    setActiveLayerId,
    frontLayerColor,
    setFrontLayerColor,
    backLayerColor,
    setBackLayerColor,
    layerColorOverrides,
  } = layerState
  const { tool, clearDraft, setActiveTool } = toolState
  const { viewport } = viewportState
  const {
    shellRef,
    showPeek,
    effectiveSecondaryPreviewMode,
    effectiveLayout,
    setActiveInspectorTab,
    handleBrowserResizeStart,
    handlePeekResizeStart,
    handleInspectorResizeStart,
    toggleInspector,
    splitterWidth,
    toolRailWidth,
    inspectorRestoreWidth,
  } = workbenchShellState
  const { fileInputRef, svgInputRef, patternPdfInputRef } = screenRefs
  const {
    activeLayer,
    activeLineType,
    patternPiecesById,
    shapeCountsByLineType,
    selectedShapeCount,
    selectedShapeIdSet,
    selectedStitchHole,
    selectedHardwareMarker,
    canUndo,
    canRedo,
    assemblyShapes,
    visibleStitchHoles,
    workspaceShapes,
    workspaceStitchHoles,
    layerColorsById,
  } = derivedState
  const {
    selectedShapes,
    selectedPatternPiece,
    selectedPieceGrainline,
    selectedPieceLabel,
    selectedPatternLabel,
    selectedPieceSeamAllowance,
    selectedPieceSeamConnections,
    selectedPieceNotches,
    selectedPiecePlacementLabels,
    selectedPieceInternalShapeIdSet,
    selectedPatternPieceEdgeCount,
    selectedPieceAvailableInternalShapes,
  } = patternPieceSelection
  const { handleFitView, handleResetView } = canvasController
  const {
    documentCommands,
    exportActions,
    fileActions,
    historyActions,
    selectionActions,
    layerActions,
    lineTypeActions,
    leatherImageFillActions,
    layerColorActions,
    constraintActions,
    patternPieceCommands,
    hardwareMarkerActions,
    stitchActions,
    geometryActions,
    creationController,
    themeActions,
  } = actions
  const {
    handleUpdateSelectedShapePoint,
    handleUpdateSelectedStitchHole,
    updateFoldLine,
  } = documentCommands
  const { handleExportSvg, handleExportPdf, handleExportDxf } = exportActions
  const { handleSaveJson, handleLoadPreset } = fileActions
  const { handleUndo, handleRedo } = historyActions
  const {
    handleCopySelection,
    handlePasteClipboard,
    handleDeleteSelection,
    handleRotateSelection,
    handleScaleSelection,
  } = selectionActions
  const {
    handleOpenSpecifyRotationModal,
    handleOpenSpecifyScaleModal,
    handleSetAsRotationCenter,
    handleClearRotationCenter,
    handleSetAsSnapPoint,
    handleClearSnapPoint,
  } = actions.transformActions
  const {
    handleShowAllLayers,
    handleHideOtherLayers,
    handleMergeActiveLayerIntoBelow,
    handleFlattenAllLayers,
  } = layerActions
  const {
    handleAddEdgeConstraintFromSelection,
    handleAddAlignConstraintsFromSelection,
    handleApplyConstraints,
    handleAlignSelection,
    handleAlignSelectionToGrid,
    handleApplySeamAllowanceToSelection,
    handleClearSeamAllowanceOnSelection,
    handleBevelSelectedCorner,
    handleRoundSelectedCorner,
    handleCreateOffsetGeometryFromSelection,
  } = constraintActions
  const {
    handleAssignSelectedToActiveLineType,
    handleClearShapeSelection,
    handleIsolateActiveLineType,
    handleSelectShapesByActiveLineType,
    handleShowAllLineTypes,
    handleUpdateActiveLineTypeColor,
    handleUpdateActiveLineTypeIgnoreInPrint,
    handleUpdateActiveLineTypeRole,
    handleUpdateActiveLineTypeStyle,
    handleUpdateActiveLineTypeStrokeWidthMm,
  } = lineTypeActions
  const {
    handleImportLeatherImageFill,
    handleUpdateLeatherImageFill,
    handleDeleteActiveLeatherImageFill,
    handleAssignSelectedToActiveLeatherImageFill,
    handleClearSelectedFromActiveLeatherImageFill,
  } = leatherImageFillActions
  const {
    handleSetLayerColorOverride,
    handleClearLayerColorOverride,
    handleResetLayerColors,
  } = layerColorActions
  const {
    ensurePatternPieceSupportRecords,
    openSelectedPatternPieceInspector,
    handleCreatePatternPieceFromSelection,
    handleUpdateSelectedPatternPiece,
    handleToggleSelectedPieceInternalShape,
    updateSelectedLabel,
    handleUpdateSelectedPieceGrainline,
    handleUpdateSelectedPieceSeamAllowance,
    handleUpdateSelectedPieceSeamConnection,
    handleUpdateSelectedPieceNotch,
    handleAddSelectedPiecePlacementLabel,
    handleUpdateSelectedPiecePlacementLabel,
    handleDeleteSelectedPiecePlacementLabel,
  } = patternPieceCommands
  const { handleDeleteSelectedHardwareMarker, handleUpdateSelectedHardwareMarker } = hardwareMarkerActions
  const {
    handleAutoPlaceFixedPitchStitchHoles,
    handleAutoPlaceVariablePitchStitchHoles,
    handleResequenceSelectedStitchHoles,
    handleSelectNextStitchHole,
    handleCountStitchHolesOnSelectedShapes,
    handleClearAllStitchHoles,
  } = stitchActions
  const {
    handleConvertArcToBezier,
    handleExtendOrTrimLines,
    handleMirrorShapes,
    handleLineSymmetry,
    handleMakeBezierCpSymmetric,
    handleToggleBezierOffsetLines,
    handleConvertSelectionToPaintedPart,
  } = geometryActions
  const {
    handleApplyTextDefaultsToSelection,
    handleExtractSelectedBoxStitchSources,
    handleClearSelectedBoxStitchSources,
    handleOpenBoxStitchHelperModal,
    handleMarkSelectedStitchHoleAsEnd,
    handleClearSelectedStitchHoleEnd,
  } = creationController
  const { handleSetThemeMode } = themeActions
  const handleOpenMoveDistanceModal = () => {
    setMoveCopyDistanceMode('move')
    setShowMoveCopyDistanceModal(true)
  }

  const workbenchController = useEditorWorkbenchController({
    documentName,
    patternPieces,
    patternPiecesById,
    pieceLabels,
    seamAllowances,
    pieceNotches,
    piecePlacementLabels,
    seamConnections,
    layers,
    activeLayerId,
    sketchGroups,
    activeSketchGroupId,
    tracingOverlays,
    activeTracingOverlayId,
    avatars,
    threeTextureSource,
    selectedShapes,
    selectedPatternPiece,
    selectedStitchHole,
    selectedHardwareMarker,
    selectedShapeCount,
    selectedShapeIdSet,
    snapSettings,
    setSnapSettings,
    canUndo,
    canRedo,
    workbenchRibbonTab,
    setActiveInspectorTab,
    isMobileLayout,
    workspaceMode,
    handleSaveJson,
    handleUndo,
    handleRedo,
    setShowHelpModal,
    handleFitView,
    handleResetView,
    setShowCanvasRuler,
    setShowDimensions,
    handleLoadPreset,
    setShowAnnotations,
    handleCopySelection,
    handlePasteClipboard,
    handleDeleteSelection,
    handleMoveSelectionByDistance: handleOpenMoveDistanceModal,
    handleRotateSelection,
    handleScaleSelection,
    handleOpenSpecifyRotationModal,
    handleOpenSpecifyScaleModal,
    handleSetAsRotationCenter,
    handleClearRotationCenter,
    handleSetAsSnapPoint,
    handleClearSnapPoint,
    handleCreatePatternPieceFromSelection,
    openSelectedPatternPieceInspector,
    handleApplySeamAllowanceToSelection,
    setShowNestingModal,
    handleAutoPlaceFixedPitchStitchHoles,
    handleAutoPlaceVariablePitchStitchHoles,
    handleCountStitchHolesOnSelectedShapes,
    handleResequenceSelectedStitchHoles,
    handleSelectNextStitchHole,
    handleClearAllStitchHoles,
    fileInputRef,
    svgInputRef,
    patternPdfInputRef,
    handleExportSvg,
    handleExportPdf,
    handleExportDxf,
    setShowExportModal,
    setShowExportOptionsModal,
    setShowPrintPreviewModal,
    setShowOptionsModal,
    setShowLocalProjectsModal,
    setShowTemplateRepositoryModal,
    setShowTracingModal,
    setShowAiBuilderModal,
    handleConvertArcToBezier,
    handleExtendOrTrimLines,
    handleMirrorShapes,
    handleLineSymmetry,
    handleMakeBezierCpSymmetric,
    handleToggleBezierOffsetLines,
    setShowChangeShapeSizeModal,
    setShowStitchSimulatorModal,
    setShowBoxStitchHelperModal,
    setShowBoxStitchModal,
    setShowWizardModal,
    setShowMandalaModal,
    setShowLetterStampModal,
    ensurePatternPieceSupportRecords,
    setSelectedShapeIds,
    setActiveLayerId,
    clearDraft,
    setActiveSketchGroupId,
    setActiveTracingOverlayId,
    setLayers,
    setTracingOverlays,
    setSecondaryPreviewMode,
    setWorkspaceMode,
    runPrecisionCommand: canvasController.runPrecisionCommand,
  })
  // Any mode that shows the model needs the 3D lane loaded, not just the mode
  // where it is the only surface.
  const shouldLoadThreeWorkbench = workspaceMode !== '2d'
  const selectionInspectorProps = buildSelectionInspectorProps({
    context: workbenchController.selectionContext,
    selectedShapeCount,
    selectedEditableShape,
    selectedStitchHole,
    selectedHardwareMarker,
    shapeCount: shapes.length,
    layerCount: layers.length,
    handleAlignSelection,
    handleAlignSelectionToGrid,
    handleCreateOffsetGeometryFromSelection,
    handleConvertSelectionToPaintedPart: () => handleConvertSelectionToPaintedPart(),
    handleOpenBoxStitchHelperModal,
    handleBevelSelectedCorner,
    handleRoundSelectedCorner,
    handleAddEdgeConstraintFromSelection,
    handleAddAlignConstraintsFromSelection,
    handleApplyConstraints,
    handleCreatePatternPieceFromSelection,
    openSelectedPatternPieceInspector,
    canOpenPieceTab: selectedPatternPiece !== null,
    handleApplySeamAllowanceToSelection,
    handleClearSeamAllowanceOnSelection,
    handleApplyTextDefaultsToSelection,
    handleExtractSelectedBoxStitchSources,
    handleClearSelectedBoxStitchSources,
    handleUpdateSelectedShapePoint,
    handleUpdateSelectedStitchHole,
    handleMarkSelectedStitchHoleAsEnd,
    handleClearSelectedStitchHoleEnd,
    handleUpdateSelectedHardwareMarker,
    handleDeleteSelectedHardwareMarker,
  })
  const pieceInspectorContentProps = buildPieceInspectorContentProps({
    selectedPatternPiece,
    selectedPieceGrainline,
    selectedPieceLabel,
    selectedPatternLabel,
    selectedPieceSeamAllowance,
    selectedPieceSeamConnections,
    selectedPieceNotches,
    selectedPiecePlacementLabels,
    selectedPatternPieceEdgeCount,
    selectedPieceAvailableInternalShapes,
    selectedPieceInternalShapeIdSet,
    handleUpdateSelectedPatternPiece,
    handleToggleSelectedPieceInternalShape,
    handleUpdateSelectedPieceGrainline,
    updateSelectedLabel,
    handleUpdateSelectedPieceSeamAllowance,
    handleUpdateSelectedPieceSeamConnection,
    setSeamConnections,
    handleUpdateSelectedPieceNotch,
    setPieceNotches,
    handleAddSelectedPiecePlacementLabel,
    handleUpdateSelectedPiecePlacementLabel,
    handleDeleteSelectedPiecePlacementLabel,
  })
  const documentInspectorProps = buildDocumentInspectorProps({
    displayUnit,
    setDisplayUnit,
    gridSpacing,
    setGridSpacing,
    showCanvasRuler,
    setShowCanvasRuler,
    showDimensions,
    setShowDimensions,
    showAnnotations,
    setShowAnnotations,
    sketchWorkspaceMode,
    setSketchWorkspaceMode,
    themeMode,
    handleSetThemeMode,
    snapSettings,
    setSnapSettings,
    projectMemo,
    setProjectMemo,
    activeLineType,
    lineTypes,
    shapeCountsByLineType,
    selectedShapeCount,
    handleAssignSelectedToActiveLineType,
    handleClearShapeSelection,
    handleIsolateActiveLineType,
    handleSelectShapesByActiveLineType,
    setActiveLineTypeId,
    handleShowAllLineTypes,
    setLineTypes,
    handleUpdateActiveLineTypeColor,
    handleUpdateActiveLineTypeIgnoreInPrint,
    handleUpdateActiveLineTypeRole,
    handleUpdateActiveLineTypeStyle,
    handleUpdateActiveLineTypeStrokeWidthMm,
    leatherImageFills,
    activeLeatherImageFill: leatherImageFills.find((fill) => fill.id === activeLeatherImageFillId) ?? null,
    setActiveLeatherImageFillId,
    handleImportLeatherImageFill,
    handleUpdateLeatherImageFill,
    handleDeleteActiveLeatherImageFill,
    handleAssignSelectedToActiveLeatherImageFill,
    handleClearSelectedFromActiveLeatherImageFill,
    layers,
    activeLayer,
    handleShowAllLayers,
    handleHideOtherLayers,
    handleMergeActiveLayerIntoBelow,
    handleFlattenAllLayers,
    layerColorsById,
    layerColorOverrides,
    frontLayerColor,
    backLayerColor,
    setFrontLayerColor,
    setBackLayerColor,
    handleSetLayerColorOverride,
    handleClearLayerColorOverride,
    handleResetLayerColors,
    onRunCadCommand: canvasController.runPrecisionCommand,
  })
  const workbenchProps = buildWorkbenchProps({
    controller: workbenchController,
    shellRef,
    workspaceMode,
    secondaryPreviewMode: effectiveSecondaryPreviewMode,
    showPeek,
    browserWidth: effectiveLayout.browserWidth,
    inspectorWidth: effectiveLayout.inspectorWidth,
    inspectorOpen: effectiveLayout.inspectorOpen,
    inspectorRestoreWidth,
    peekWidth: effectiveLayout.peekWidth,
    splitterWidth,
    toolRailWidth,
    activeRibbonTab: workbenchRibbonTab,
    themeMode,
    onSetRibbonTab: setWorkbenchRibbonTab,
    onSetThemeMode: handleSetThemeMode,
    setLayers,
    tool,
    onSetActiveTool: setActiveTool,
    activeInspectorTab: effectiveLayout.activeInspectorTab,
    onSetActiveInspectorTab: setActiveInspectorTab,
    onStartBrowserResize: handleBrowserResizeStart,
    onStartPeekResize: handlePeekResizeStart,
    onStartInspectorResize: handleInspectorResizeStart,
    onToggleInspector: toggleInspector,
    zoomScale: viewport.scale,
    displayUnit,
    activeLayer,
    activeLineType,
    onTogglePrecision: () => setShowPrecisionModal((previous) => !previous),
  })
  const workbenchThreeWorkspaceProps = buildWorkbenchThreeWorkspaceProps({
    workspaceMode,
    shapes: sketchWorkspaceMode === 'assembly' ? assemblyShapes : workspaceShapes,
    selectedShapeIds,
    stitchHoles: sketchWorkspaceMode === 'assembly' ? visibleStitchHoles : workspaceStitchHoles,
    stitchThreadColor,
    onSetStitchThreadColor: setStitchThreadColor,
    patternPieces,
    pieceInterfaces,
    assemblyConnections,
    piecePlacements3d,
    seamConnections,
    hardwareMarkers,
    threePreviewSettings,
    avatars,
    onSetPiecePlacements3d: setPiecePlacements3d,
    onSetThreePreviewSettings: setThreePreviewSettings,
    onSetAvatars: setAvatars,
    threeTextureSource,
    onSetThreeTextureSource: setThreeTextureSource,
    threeTextureShapeIds,
    onSetThreeTextureShapeIds: setThreeTextureShapeIds,
    foldLines,
    layers,
    lineTypes,
    themeMode: resolvedThemeMode,
    onUpdateFoldLine: updateFoldLine,
  })

  return {
    workbenchController,
    shouldLoadThreeWorkbench,
    selectionInspectorProps,
    pieceInspectorContentProps,
    documentInspectorProps,
    workbenchProps,
    workbenchThreeWorkspaceProps,
  }
}

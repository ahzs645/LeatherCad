export function getBuiltinTranslation(locale: EditorLocale, key: string): string | undefined {
  const dictionary = locale === 'ja' ? JAPANESE_UI : SHELL_DICTIONARIES[locale]
  return dictionary && Object.hasOwn(dictionary, key) ? dictionary[key] : undefined
}

export function getLocaleCoverage(locale: EditorLocale) {
  return {
    locale,
    translatedEntryCount: locale === 'en' ? 0 : Object.keys(locale === 'ja' ? JAPANESE_UI : SHELL_DICTIONARIES[locale]).length,
    scope: locale === 'en' ? 'source-language' : locale === 'ja' ? 'shell-and-main-dialogs' : 'shell-recovery-and-specialist-controls',
    fallback: 'en',
  } as const
}
